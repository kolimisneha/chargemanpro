import os

def patch_file(file_path, target_str, replacement_str):
    if not os.path.exists(file_path):
        print(f"Skipping patch: {file_path} does not exist.")
        return False
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()
    if target_str in content:
        content = content.replace(target_str, replacement_str)
        with open(file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Successfully patched: {file_path}")
        return True
    else:
        print(f"Already patched or target string not found in: {file_path}")
        return False

# 1. Patch CapacitorGoogleMaps.java imports
java_file = "node_modules/@capacitor-community/capacitor-googlemaps-native/android/src/main/java/com/hemangkumar/capacitorgooglemaps/CapacitorGoogleMaps.java"
patch_file(java_file, "com.google.android.libraries.maps", "com.google.android.gms.maps")

# 2. Patch plugin build.gradle dependency
gradle_file = "node_modules/@capacitor-community/capacitor-googlemaps-native/android/build.gradle"

with open(gradle_file, 'r', encoding='utf-8') as f:
    content = f.read()

# Make sure play-services-maps is used AND appcompat is added
if "com.google.android.libraries.maps:maps:3.1.0-beta" in content:
    content = content.replace(
        "implementation 'com.google.android.libraries.maps:maps:3.1.0-beta'",
        "implementation 'com.google.android.gms:play-services-maps:18.2.0'\n    implementation 'androidx.appcompat:appcompat:1.2.0'"
    )
elif "com.google.android.gms:play-services-maps:18.2.0" in content and "appcompat" not in content:
    content = content.replace(
        "implementation 'com.google.android.gms:play-services-maps:18.2.0'",
        "implementation 'com.google.android.gms:play-services-maps:18.2.0'\n    implementation 'androidx.appcompat:appcompat:1.2.0'"
    )

with open(gradle_file, 'w', encoding='utf-8') as f:
    f.write(content)
print(f"Patched dependency in: {gradle_file}")
